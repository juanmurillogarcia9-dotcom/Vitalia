const normalizeText = value =>
  value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase('es')

export const searchFoods = query => {
  const normalizedQuery = normalizeText(String(query ?? '').trim())
  if (!normalizedQuery) return []

  return foodCatalog.filter(food =>
    [food.name, ...(food.aliases ?? [])].some(name =>
      normalizeText(name).includes(normalizedQuery)
    )
  )
}

export const findFoodForScan = query => {
  const normalizedQuery = normalizeText(String(query ?? '').trim())
  if (!normalizedQuery) return null

  const exactMatches = foodCatalog.filter(food =>
    [food.name, ...(food.aliases ?? [])].some(
      name => normalizeText(name) === normalizedQuery
    )
  )
  if (exactMatches.length === 1) return exactMatches[0]

  const matches = searchFoods(normalizedQuery)
  return matches.length === 1 ? matches[0] : null
}

export const estimateNutrition = (food, portions = 1) => {
  const quantity = Number(portions)
  if (!food || !Number.isFinite(quantity) || quantity < 0.25 || quantity > 10) {
    throw new Error('Indica entre 0,25 y 10 porciones.')
  }

  const scale = value => Math.round(value * quantity * 10) / 10
  return {
    calories: scale(food.calories),
    protein: scale(food.protein),
    carbohydrates: scale(food.carbohydrates),
    potassium: Math.round(food.potassium * quantity)
  }
}
